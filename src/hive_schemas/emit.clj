(ns hive-schemas.emit
  "Render verification plans into source.

   Pure except `spit-ns!`.

   Levers:
     unprintable   form -> the leaves that cannot round-trip through the reader
     plan->form    Plan -> the deftriad-from-schema form that synthesizes it
     plans->forms  [Plan] -> [form]
     ns-form       an emission spec -> its (ns ...) form
     render-ns     an emission spec -> deterministic source text
     ns->path      ns symbol + extension -> the relative source path
     spit-ns!      root + an emission spec -> {:ok path} | {:error ...}"
  (:require [clojure.java.io :as io]
            [clojure.pprint :as pprint]
            [clojure.string :as str]
            [hive-schemas.plan :as plan]
            [hive-schemas.vocab :as vocab]
            [malli.core :as m]))

